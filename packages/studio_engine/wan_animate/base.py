"""Base models and protocol for Wan2.2-Animate multi-backend engine.

Follows Alibaba Coding Guidelines:
- Strict typing, 0 any in domain DTOs
- File <= 250 lines
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path
from typing import Callable, Literal, Optional
from pydantic import BaseModel, Field

ProgressCallback = Callable[[float, str, str], None]


class WanAnimateRequest(BaseModel):
    """Unified request payload for Wan2.2-Animate inference."""

    mode: Literal["replace", "move"] = Field(
        default="replace",
        description="replace: keep background & lighting, swap character; move: transfer motion to portrait",
    )
    video_path: str = Field(description="Local path to driving/source MP4 video")
    character_image_path: str = Field(description="Local path to target character portrait image")
    output_dir: str = Field(description="Directory to write generated video")
    resolution: Literal["480p", "720p"] = Field(default="720p")
    use_relighting_lora: bool = Field(default=True)
    prompt: str = Field(
        default="A person speaking naturally to the camera with realistic lighting and smooth expressions",
        description="Optional positive prompt for Wan2.2-Animate",
    )


class WanAnimateResult(BaseModel):
    """Unified result from any Wan2.2-Animate backend."""

    video_path: str = Field(description="Generated raw MP4 path (before optional audio/subtitle mux)")
    backend_id: str = Field(description="comfyui | wan_worker | dashscope | local_fallback")
    backend_label: str = Field(description="Human-readable engine badge")
    mode: str = Field(description="replace or move")
    is_neural_wan: bool = Field(default=True, description="True if generated by actual Wan2.2-Animate model")
    note: str = Field(default="")


class BackendHealth(BaseModel):
    """Health check status for a single backend."""

    backend_id: str
    label: str
    available: bool
    endpoint: str
    detail: str


class BaseWanAnimateBackend(ABC):
    """Abstract protocol for Wan2.2-Animate backends."""

    backend_id: str = "base"
    label: str = "Base Backend"

    @abstractmethod
    def check_health(self, timeout: float = 2.0) -> BackendHealth:
        """Probe whether this backend is reachable and ready."""

    @abstractmethod
    def generate(
        self,
        req: WanAnimateRequest,
        on_progress: Optional[ProgressCallback] = None,
    ) -> WanAnimateResult:
        """Run character replacement or motion animation synchronously."""
